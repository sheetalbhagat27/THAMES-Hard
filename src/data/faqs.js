// Words to ignore when scoring word matches
const STOP_WORDS = new Set([
  'the', 'is', 'at', 'which', 'on', 'a', 'an', 'and', 'or', 'in', 'of', 'for', 'to',
  'with', 'about', 'tell', 'me', 'what', 'are', 'your', 'you', 'do', 'does', 'can',
  'i', 'how', 'where', 'when', 'why', 'who', 'please', 'give'
]);

/**
 * Intelligent client-side FAQ matcher.
 * Supports case-insensitive keyword scoring, partial substring matching,
 * and direct question similarity.
 */
export function matchFAQ(query, faqs = FAQ_DATA) {
  if (!query || typeof query !== 'string') return null;

  const cleanQuery = query.toLowerCase().trim();
  if (!cleanQuery) return null;

  // 1. Direct regex greeting check
  if (/^(hi+|hello+|hey+|namaste|good\s*(morning|afternoon|evening)|hola)(\s|$|[!?.,])/i.test(cleanQuery)) {
    return faqs.find((f) => f.id === 'greeting') || null;
  }

  // Tokenize user query into clean words excluding stop words
  const queryWords = cleanQuery
    .replace(/[^\w\s]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 2 && !STOP_WORDS.has(w));

  let bestMatch = null;
  let highestScore = 0;

  for (const faq of faqs) {
    if (faq.id === 'greeting') continue; // Only matched via direct greeting check above

    let score = 0;
    const questionLower = faq.question.toLowerCase();

    // 1. Direct question match
    if (questionLower === cleanQuery) {
      score += 100;
    } else if (questionLower.includes(cleanQuery)) {
      score += 60;
    } else if (cleanQuery.includes(questionLower)) {
      score += 50;
    }

    // 2. Keyword matching with weighted scoring
    if (Array.isArray(faq.keywords)) {
      for (const kw of faq.keywords) {
        const kwLower = kw.toLowerCase();

        // Exact keyword phrase match in user query
        if (cleanQuery === kwLower) {
          score += 45;
        } else if (cleanQuery.includes(kwLower)) {
          // Multi-word phrase matches get higher weight
          score += kwLower.includes(' ') ? 30 : 15;
        }

        // Substring / word-level match
        for (const word of queryWords) {
          if (kwLower === word) {
            score += 10;
          } else if (kwLower.length >= 4 && kwLower.includes(word)) {
            score += 5;
          }
        }
      }
    }

    // 3. Question word overlap
    for (const word of queryWords) {
      if (questionLower.includes(word)) {
        score += 4;
      }
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = faq;
    }
  }

  // Minimum threshold to avoid false positives on unrelated input
  if (highestScore >= 12) {
    return bestMatch;
  }

  return null;
}
